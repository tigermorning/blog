# 11강 review()/route() 로직 검증 — LLM 호출 없는 순수 함수라 로컬 재현 가능.
# 강의 코드 그대로(get_page_text/monaco에서 꺼낸 원문) + 가상 state로 세 가지 확인:
#  1. 재위임된 절(sections에 같은 "절" 두 벌)이 latest 딕셔너리에서 마지막 것만 남는지
#  2. 종료 조건 둘(재위임 off / 바퀴 소진)이 정확히 동작하는지
#  3. gaps 있을 때 newtoc[i]["지시"]에 "(재위임: ...)" 문구가 실제로 붙는지

설정 = {"재위임": True, "최대바퀴": 3}


def review(s: dict) -> dict:
    latest = {}
    for sec in s["sections"]:
        latest[sec["절"]] = sec
    toc = s["plan"]["목차"]
    wheel = s["plan"].get("바퀴", 1)
    if not 설정["재위임"] or wheel >= 설정["최대바퀴"]:
        gaps = []
    else:
        gaps = [i for i, t in enumerate(toc)
                if not latest.get(t["절"], {}).get("충분", False)]
    if not gaps:
        why = "루프 없음" if not 설정["재위임"] else ("바퀴 소진" if wheel >= 설정["최대바퀴"] else "빈 칸 없음")
        return {"plan": {**s["plan"], "배치": [], "종료": why},
                "log": [f"④ 점검   {len(toc)}절 중 빈 칸 {len(gaps)}개 — 종합으로 ({why})"]}
    newtoc = [dict(t) for t in toc]
    for i in gaps:
        prev = latest.get(toc[i]["절"], {})
        newtoc[i]["지시"] = (f"{toc[i]['지시']} (재위임: 지난번에 «{'», «'.join(prev.get('읽은문서', [])) or '없음'}» "
                             f"를 읽었지만 {prev.get('부족', '근거가 모자랐다')}. 그 빈 칸을 겨냥해 "
                             "아직 안 본 문서를 찾아라)")
    return {"plan": {**s["plan"], "목차": newtoc, "배치": gaps, "바퀴": wheel + 1},
            "log": [f"④ 점검   {len(toc)}절 중 빈 칸 {len(gaps)}개 — "
                    f"«{'», «'.join(toc[i]['절'][:12] for i in gaps)}» 재위임"]}


def route(s: dict) -> str:
    return "more" if s["plan"].get("배치") else "done"


toc = [
    {"절": "원인", "지시": "동학농민운동의 배경을 써라"},
    {"절": "전개", "지시": "1894년 사건 전개를 시간순으로 써라"},
    {"절": "인물", "지시": "주요 인물을 정리하라"},
    {"절": "결과", "지시": "사건의 결과를 정리하라"},
]

print("=== 케이스 1: 1바퀴, 절 두 개가 부족 신고 ===")
s1 = {
    "plan": {"목차": toc, "바퀴": 1},
    "sections": [
        {"절": "원인", "충분": True, "읽은문서": ["동학 농민 혁명"], "부족": ""},
        {"절": "전개", "충분": False, "읽은문서": ["청일 전쟁"], "부족": "날짜별 사건이 두 건뿐이었다"},
        {"절": "인물", "충분": True, "읽은문서": ["전봉준"], "부족": ""},
        {"절": "결과", "충분": False, "읽은문서": ["갑오개혁"], "부족": "결과 서술이 한 문단에 그쳤다"},
    ],
}
r1 = review(s1)
for line in r1["log"]:
    print(line)
print("route:", route(r1))
print("배치(gaps):", r1["plan"]["배치"])
print("바퀴:", r1["plan"]["바퀴"])
assert r1["plan"]["배치"] == [1, 3], "전개·결과 두 절만 gaps로 잡혀야 함"
assert r1["plan"]["바퀴"] == 2, "바퀴가 1에서 2로 올라가야 함"
assert "(재위임:" in r1["plan"]["목차"][1]["지시"], "지시문에 재위임 겨냥 문구가 붙어야 함"
assert "날짜별 사건이 두 건뿐이었다" in r1["plan"]["목차"][1]["지시"], "부족 사유가 지시문에 그대로 실려야 함"
assert "(재위임:" not in r1["plan"]["목차"][0]["지시"], "충분 신고한 절은 지시문이 안 바뀌어야 함"
print("케이스 1 검증 통과\n")

print("=== 케이스 2: 재위임된 절이 sections에 두 벌 쌓였을 때(리듀서 덧붙임 재현) ===")
